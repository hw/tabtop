// The pictures 3D printing files have of themselves (model-thumbnails.js):
// G-code's comments, binary G-code's blocks, a 3MF's entry; read only in
// the parts asked for.
import test from "node:test";
import assert from "node:assert/strict";
import { deflateRawSync } from "node:zlib";
import { modelThumbnail, modelThumbnailed } from "../tabtopd/model-thumbnails.js";

// Small real pictures: PNGs (1×1 and 2×2, by their headers, as the files
// say) and a JPEG's first bytes.
const png = (w) => Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), Buffer.from(`IHDR${w}`), Buffer.alloc(20, w)]);
const jpeg = Buffer.concat([Buffer.from([0xff, 0xd8, 0xff, 0xe0]), Buffer.alloc(40, 7)]);

// reader reads bytes, counting what's asked for.
function reader(bytes) {
    const asked = [];
    const read = async (offset, length) => { asked.push([offset, length]); return new Uint8Array(bytes.subarray(offset, offset + length)); };
    return { read, asked };
}
const base64Lines = (b) => b.toString("base64").match(/.{1,78}/g).map((l) => `; ${l}`).join("\n");
const gcodeBlock = (tag, w, h, b) => `;\n; ${tag} begin ${w}x${h} ${b.toString("base64").length}\n${base64Lines(b)}\n; ${tag} end\n;\n`;

test("which files have pictures of themselves", () => {
    for (const n of ["a.3mf", "B.GCODE", "c.gco", "d.bgcode"]) assert.ok(modelThumbnailed(n), n);
    for (const n of ["e.stl", "f.gcode.txt", "g.obj"]) assert.ok(!modelThumbnailed(n), n);
});

test("G-code: the largest PNG or JPEG in its comments (not QOI); only its start read", async () => {
    const small = png(1), big = png(2);
    const text = "; generated by PrusaSlicer 2.9.2\n" + gcodeBlock("thumbnail", 16, 16, small) + gcodeBlock("thumbnail_QOI", 400, 400, Buffer.from("qoifxxxx"))
        + gcodeBlock("thumbnail", 220, 124, big) + gcodeBlock("thumbnail_JPG", 100, 100, jpeg) + "G1 X1 Y1\n".repeat(400000);
    const bytes = Buffer.from(text);
    const { read, asked } = reader(bytes);
    const got = await modelThumbnail("p.gcode", bytes.length, read);
    assert.equal(got.type, "image/png");
    assert.deepEqual(Buffer.from(got.bytes), big);
    assert.deepEqual(asked, [[0, 2 << 20]]);
    // Bambu Studio's and Orca's: the same, inside a block of their own; Cura's, JPEG alone.
    const bambu = Buffer.from(`; HEADER_BLOCK_START\n; THUMBNAIL_BLOCK_START\n${gcodeBlock("thumbnail", 300, 300, small)}; THUMBNAIL_BLOCK_END\n`);
    assert.deepEqual(Buffer.from((await modelThumbnail("b.gcode", bambu.length, reader(bambu).read)).bytes), small);
    const cura = Buffer.from(`;FLAVOR:Marlin\n${gcodeBlock("thumbnail_JPG", 300, 300, jpeg)}`);
    assert.equal((await modelThumbnail("c.gco", cura.length, reader(cura).read)).type, "image/jpeg");
    // None; one cut off by the end of what's read; one not a picture at all.
    assert.equal(await modelThumbnail("n.gcode", 8, reader(Buffer.from("G1 X1\n")).read), null);
    const cut = Buffer.from(gcodeBlock("thumbnail", 16, 16, small).slice(0, 60));
    assert.equal(await modelThumbnail("x.gcode", cut.length, reader(cut).read), null);
    const fake = Buffer.from(gcodeBlock("thumbnail", 16, 16, Buffer.from("<svg onload=alert(1)>")));
    assert.equal(await modelThumbnail("f.gcode", fake.length, reader(fake).read), null);
});

test("binary G-code: its largest PNG or JPEG thumbnail block, before its G-code", async () => {
    const block = (type, params, data) => {
        const h = Buffer.alloc(8);
        h.writeUInt16LE(type, 0); h.writeUInt16LE(0, 2); h.writeUInt32LE(data.length, 4);
        return Buffer.concat([h, params, data, Buffer.alloc(4)]); // (and its CRC: checksums on)
    };
    const thumb = (format, w, h, data) => { const p = Buffer.alloc(6); p.writeUInt16LE(format, 0); p.writeUInt16LE(w, 2); p.writeUInt16LE(h, 4); return block(5, p, data); };
    const head = Buffer.alloc(10);
    head.write("GCDE", 0); head.writeUInt32LE(1, 4); head.writeUInt16LE(1, 8);
    const small = png(1), big = png(2);
    const file = Buffer.concat([head, block(0, Buffer.alloc(2), Buffer.from("Producer=PrusaSlicer\n")), thumb(0, 16, 16, small), thumb(2, 800, 800, Buffer.from("qoif")),
        thumb(1, 300, 300, jpeg), thumb(0, 400, 300, big), block(1, Buffer.alloc(2), Buffer.from("G1 X1\n")), thumb(0, 999, 999, png(3))]);
    const got = await modelThumbnail("p.bgcode", file.length, reader(file).read);
    assert.deepEqual(Buffer.from(got.bytes), big, "the largest before its G-code");
    assert.equal(await modelThumbnail("n.bgcode", 10, reader(Buffer.from("not bgcode")).read), null);
});

test("3MF: its own picture, else a plate's (not a pick map); its directory and the one entry read", async () => {
    // A ZIP: each entry stored or Deflate'd, its directory after, then its end.
    const zip = (entries) => {
        const locals = [], central = [];
        let offset = 0;
        for (const [name, data, deflate] of entries) {
            const packed = deflate ? deflateRawSync(data) : data, n = Buffer.from(name);
            const l = Buffer.alloc(30);
            l.writeUInt32LE(0x04034b50, 0); l.writeUInt16LE(deflate ? 8 : 0, 8); l.writeUInt32LE(packed.length, 18); l.writeUInt32LE(data.length, 22); l.writeUInt16LE(n.length, 26);
            const c = Buffer.alloc(46);
            c.writeUInt32LE(0x02014b50, 0); c.writeUInt16LE(deflate ? 8 : 0, 10); c.writeUInt32LE(packed.length, 20); c.writeUInt32LE(data.length, 24); c.writeUInt16LE(n.length, 28); c.writeUInt32LE(offset, 42);
            locals.push(l, n, packed);
            central.push(c, n);
            offset += 30 + n.length + packed.length;
        }
        const dir = Buffer.concat(central), end = Buffer.alloc(22);
        end.writeUInt32LE(0x06054b50, 0); end.writeUInt32LE(dir.length, 12); end.writeUInt32LE(offset, 16);
        return Buffer.concat([...locals, dir, end]);
    };
    const model = Buffer.alloc(300000, 0x41);
    const own = png(2), plate = png(1);
    let file = zip([["3D/3dmodel.model", model, true], ["Metadata/pick_1.png", png(3), false], ["Metadata/plate_1.png", plate, true], ["Metadata/thumbnail.png", own, true]]);
    let { read, asked } = reader(file);
    assert.deepEqual(Buffer.from((await modelThumbnail("p.3mf", file.length, read)).bytes), own);
    assert.ok(asked.every(([, length]) => length < 70000), `only small parts read: ${JSON.stringify(asked)}`);
    // Bambu Studio's: a plate's picture, not its pick map.
    file = zip([["Metadata/pick_1.png", png(3), false], ["Metadata/plate_1.png", plate, false], ["3D/3dmodel.model", model, true]]);
    assert.deepEqual(Buffer.from((await modelThumbnail("b.3mf", file.length, reader(file).read)).bytes), plate);
    // None; or one that isn't a picture; or one that says it's smaller than it unpacks to.
    file = zip([["3D/3dmodel.model", model, true]]);
    assert.equal(await modelThumbnail("n.3mf", file.length, reader(file).read), null);
    file = zip([["Metadata/thumbnail.png", Buffer.from("<html>"), false]]);
    assert.equal(await modelThumbnail("h.3mf", file.length, reader(file).read), null);
    file = zip([["Metadata/thumbnail.png", Buffer.concat([own, Buffer.alloc(100000)]), true]]);
    file.writeUInt32LE(own.length, file.length - 22 - (46 + "Metadata/thumbnail.png".length) + 24); // its directory's size, too small
    await assert.rejects(modelThumbnail("lie.3mf", file.length, reader(file).read), /unpacks to more/);
    assert.equal(await modelThumbnail("z.3mf", 5, reader(Buffer.from("hello")).read), null);
});
