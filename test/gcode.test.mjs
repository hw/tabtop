    let g = gcode("G1 X1 E1\nG1 X200000 E3\nG1 Y-1000000 E3.5\nG1 X2 E4\nG2 X3 I-500000 J0 E5\nG2 X4 R1000000000 E6\nG1 X5 E7\n");
