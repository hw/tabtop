test("a mesh's size, triangles and volume; several together", () => {
    // A tetrahedron with legs of 10: 1000/6 mm³, inside out or not.
    const P = [0, 0, 0, 10, 0, 0, 0, 10, 0, 0, 0, 10];
    const F = [0, 2, 1, 0, 1, 3, 0, 3, 2, 1, 2, 3];
    const f = meshFacts(Float32Array.from(P), Uint32Array.from(F));
    assert.equal(f.triangles, 4);
    near(f.volume, 1000 / 6);
    assert.deepEqual(f.min, [0, 0, 0]);
    assert.deepEqual(f.max, [10, 10, 10]);
    near(meshFacts(Float32Array.from(P), Uint32Array.from(F.slice().reverse())).volume, 1000 / 6);
    // Not indexed: three corners each.
    const flat = Float32Array.from(F.flatMap((i) => P.slice(i * 3, i * 3 + 3)));
    near(meshFacts(flat).volume, 1000 / 6);
    const both = combine([f, { ...f, min: [20, 0, 0], max: [30, 10, 10] }]);
    assert.equal(both.triangles, 8);
    assert.deepEqual(both.max, [30, 10, 10]);
    assert.equal(describeMesh(f), "10 × 10 × 10 mm · 4 triangles · 0.17 cm³");
});

// zip builds a zip whose central directory says its files are sizes long
// (their contents aren't there: only what's said of them is read).
function zip(sizes) {
    const records = sizes.map((size, i) => {
        const name = new TextEncoder().encode(`f${i}`);
        const r = new DataView(new ArrayBuffer(46 + name.length));
        r.setUint32(0, 0x02014b50, true);
        r.setUint32(24, size, true);
        r.setUint16(28, name.length, true);
        const bytes = new Uint8Array(r.buffer);
        bytes.set(name, 46);
        return bytes;
    });
    const dirLength = records.reduce((n, r) => n + r.length, 0);
    const out = new Uint8Array(dirLength + 22);
    let at = 0;
    for (const r of records) { out.set(r, at); at += r.length; }
    const end = new DataView(out.buffer, at);
    end.setUint32(0, 0x06054b50, true);
    end.setUint16(8, sizes.length, true);
    end.setUint16(10, sizes.length, true);
    end.setUint32(12, dirLength, true);
    end.setUint32(16, 0, true);
    return out;
}

test("a zipped model too big to unpack is said to be, before it's tried", () => {
    assert.equal(zipTooBig(zip([1000, 2000])), "");
    assert.match(zipTooBig(zip([MAX_UNZIPPED / 2, MAX_UNZIPPED / 2 + 1])), /more than 400 MB/);
    assert.match(zipTooBig(zip([0xffffffff])), /more than 400 MB/);
    // Its "total" count saying none, its count "on this disk" (which fflate
    // unpacks by) saying two: counted as fflate would.
    const lying = zip([MAX_UNZIPPED / 2, MAX_UNZIPPED / 2 + 1]);
    new DataView(lying.buffer).setUint16(lying.length - 22 + 10, 0, true);
    assert.match(zipTooBig(lying), /more than 400 MB/);
    // With a limit of its own (an AMF's, read on the page).
    assert.equal(zipTooBig(zip([1 << 20]), 2 << 20), "");
    assert.match(zipTooBig(zip([3 << 20]), 2 << 20), /more than 2 MB/);
    const damaged = zip([10]);
    damaged[0] = 0;
    assert.equal(zipTooBig(damaged), "its file list is damaged");
    assert.equal(zipTooBig(new TextEncoder().encode("solid not a zip")), "");
});

test("each extrusion's speed, temperature, fan, width, height and flow", () => {
    // 1.75 mm filament (said): its area, π·0.875².
    const area = Math.PI * 0.875 ** 2;
    const g = gcode(`; filament_diameter = 1.75
M104 S205
M106 S128
G1 Z0.2 F600
;WIDTH:0.5
;HEIGHT:0.2
G1 X10 E1 F1800
M107
M109 S215
G1 X20 E2 F3000
M104 T1 S250
`);
    const x = g.extrude;
    assert.deepEqual([...x.speed], [30, 50]);
    assert.deepEqual([...x.temp], [205, 215]);
    assert.deepEqual([...x.fan], [128, 0]);
    near(x.width[0], 0.5);
    near(x.height[0], 0.2);
    // Flow: filament pushed a mm (0.1), its area, the speed.
    near(x.flow[0], 0.1 * area * 30);
    assert.equal(g.filamentDiameter, 1.75);
    assert.equal(g.diameterGuessed, false);
    // Not said: its width from what's pushed, a line's sides rounded; its height, its layer's.
    const w = gcode("; filament_diameter = 1.75\nG1 Z0.3 F1200\nG1 X10 E0.4\nG1 Z0.6\nG1 X0 E0.8\n").extrude;
    const expected = 0.04 * area / 0.3 + 0.3 * (1 - Math.PI / 4);
    near(w.width[0], expected);
    near(w.height[0], 0.3);
    near(w.height[1], 0.3);
    // An arc's: its length along the arc.
    const arc = gcode("; filament_diameter = 1.75\nG1 Z0.2 F600\nG1 X10 Y0\nG3 X-10 Y0 I-10 J0 E3.14159\n").extrude;
    for (const f of arc.flow) near(f, 0.1 * area * 10, 1e-3);
});

