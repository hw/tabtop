test("moves: absolute and relative, E as M82/M83 say (G91 too), G92, G28, inches", () => {
    // M83 after G90 keeps E relative; G91 makes everything relative.
    let g = gcode("G90\nM83\nG1 X10 E1\nG1 X20 E1\nG91\nG1 X5 E1\nG90\nG1 X0 E1\n");
    assert.deepEqual(segments(g), [[0, 0, 0, 10, 0, 0], [10, 0, 0, 20, 0, 0], [20, 0, 0, 25, 0, 0], [25, 0, 0, 0, 0, 0]]);
    near(g.filament, 4);
    // Absolute E: retracting and priming in place draw nothing; G92 E0 resets.
    g = gcode("M82\nG1 X10 E5\nG1 E4\nG1 E5\nG92 E0\nG1 X20 E2\nG1 X30 E1\n");
    assert.deepEqual(segments(g), [[0, 0, 0, 10, 0, 0], [10, 0, 0, 20, 0, 0]]);
    assert.deepEqual(segments(g, "travel"), [[20, 0, 0, 30, 0, 0]]);
    near(g.filament, 5 + 2);  // (priming in place isn't laid down)
    // G92 places it; G28 X homes X alone; G20 is inches.
    g = gcode("G92 X100 Y50\nG1 X101 E1\nG28 X\nG1 Y51 E2\nG20\nG1 X1 E2.1\n");
    assert.deepEqual(segments(g), [[100, 50, 0, 101, 50, 0], [0, 50, 0, 0, 51, 0], [0, 51, 0, 25.4, 51, 0]]);
    // Line numbers, checksums, comments in brackets, lower case, no spaces.
    g = gcode("N10 G1 X1 E1*71\nn11 g1x2 (a comment) e2 ; and another\n");
    assert.deepEqual(segments(g), [[0, 0, 0, 1, 0, 0], [1, 0, 0, 2, 0, 0]]);
});

test("arcs: by I and J, by R, a whole circle, a helix", () => {
    // A quarter, anticlockwise, about (0, 0), radius 10.
    let g = gcode("G1 X10 Y0\nG3 X0 Y10 I-10 J0 E1\n");
    const p = segments(g);
    assert.ok(p.length > 20);
    assert.deepEqual(p[0].slice(0, 3), [10, 0, 0]);
    assert.deepEqual(p.at(-1).slice(3), [0, 10, 0]);
    for (const s of p) near(Math.hypot(s[3], s[4]), 10, 1e-3);
    // The same, clockwise by R, goes the other way round: through y < 0.
    g = gcode("G1 X10 Y0\nG2 X0 Y10 R-10 E1\n");
    assert.ok(segments(g).some((s) => s[4] < -5));
    // Start and end the same: a whole circle.
    g = gcode("G1 X10 Y0\nG2 X10 Y0 I-10 J0 E1\n");
    const all = segments(g);
    assert.ok(all.some((s) => s[3] < -9.9));
    near(all.reduce((n, s) => n + Math.hypot(s[3] - s[0], s[4] - s[1]), 0), 2 * Math.PI * 10, 0.05);
    // Rising as it turns.
    g = gcode("G1 X10 Y0\nG3 X-10 Y0 Z2 I-10 J0 E1\n");
    near(segments(g).at(-1)[5], 2);
});

