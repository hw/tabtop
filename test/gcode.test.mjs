const fixture = (name) => new Uint8Array(readFileSync(new URL(`data/3d/${name}`, import.meta.url)));
const gcode = (text, opts) => parseGCode(new TextEncoder().encode(text), opts);
const segments = (g, kind = "extrude") => {
    const p = g[kind].positions, out = [];
    for (let i = 0; i < p.length; i += 6) out.push([...p.subarray(i, i + 6)].map((v) => Math.round(v * 1000) / 1000));
    return out;
};
const near = (a, b, eps = 1e-3) => assert.ok(Math.abs(a - b) < eps, `${a} isn't ${b}`);

// The fixtures are a 12 mm, 24-sided prism, 6 mm tall (prism.stl), sliced
// at 0.3 mm: by PrusaSlicer 2.9.2, as it is and with arcs (G2/G3), and by
// CuraEngine 5.0.0.
test("PrusaSlicer's G-code: its layers, its kinds, and the filament it says it uses", () => {
    for (const name of ["prusa.gcode", "prusa-arcs.gcode"]) {
        const bytes = fixture(name);
        const g = parseGCode(bytes);
        const said = Number(/filament used \[mm\] = ([\d.]+)/.exec(new TextDecoder().decode(bytes))[1]);
        assert.equal(g.layers.z.length, 20, name);
        near(g.filament, said, 0.01);
        near(g.layers.z[0], 0.35);
        near(g.layers.z[19], 6.05);
        assert.match(g.slicer, /^PrusaSlicer 2\.9\.2/);
        assert.ok(g.time > 150 && g.time < 250, `${name}: ${g.time}`);
        assert.deepEqual(new Set(g.types.slice(1).map(featureCategory)),
            new Set(["other", "skirt", "inner-wall", "outer-wall", "solid-infill", "infill", "bridge", "top-bottom"]));
        // Each layer's segments end where the next one's begin, in order.
        for (let i = 1; i < 20; i++) assert.ok(g.layers.extrudeEnd[i] > g.layers.extrudeEnd[i - 1]);
        assert.equal(g.layers.extrudeEnd[19], g.extrude.types.length);
        assert.equal(g.layers.travelEnd[19], g.travel.positions.length / 6);
    }
    // Arcs drawn as the lines they replace: the same footprint, to a hair.
    const lines = parseGCode(fixture("prusa.gcode")).bounds, arcs = parseGCode(fixture("prusa-arcs.gcode")).bounds;
    for (let c = 0; c < 3; c++) {
        near(lines.min[c], arcs.min[c], 0.1);
        near(lines.max[c], arcs.max[c], 0.1);
    }
});

