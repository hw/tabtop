//go:build ignore

// Regenerate browser and classic-worker registries from file-types.json.
package main

import (
	"encoding/json"
	"fmt"
	"os"
)

func main() {
	data, err := os.ReadFile("file-types.json")
	if err != nil {
		panic(err)
	}
	var registry map[string]any
	if err = json.Unmarshal(data, &registry); err != nil {
		panic(err)
	}
	encoded, err := json.MarshalIndent(registry, "", "  ")
	if err != nil {
		panic(err)
	}
	for name, prefix := range map[string]string{"file-types.js": "export const FILE_TYPES = Object.freeze(", "file-types-worker.js": "self.TabTopFileTypes = Object.freeze("} {
		content := fmt.Sprintf("// Generated by go generate from file-types.json. Do not edit.\n%s%s);\n", prefix, encoded)
		if err = os.WriteFile(name, []byte(content), 0644); err != nil {
			panic(err)
		}
	}
}
