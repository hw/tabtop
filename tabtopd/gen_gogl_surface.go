// Regenerate gogl-surface.js from gogl-surface.json: the WebGL the mirror
// records, forwards and replays, for the page's hook (gogl.js, inside
// goGLPageJS's function) and the viewer (go-frame-gl.js, a script before
// it). The server embeds the JSON itself (gocanvasgl.go).
//
// go run gen_gogl_surface.go [dir]: dir is where gogl-surface.js is
// written, "." if not given (TestGoGLSurfaceGenerated writes it elsewhere).
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
)

func main() {
	data, err := os.ReadFile("gogl-surface.json")
	if err != nil {
		panic(err)
	}
	if !json.Valid(data) {
		panic("gogl-surface.json isn't JSON")
	}
	dir := "."
	if len(os.Args) > 1 {
		dir = os.Args[1]
	}
	content := fmt.Sprintf("// Generated by go generate from gogl-surface.json. Do not edit.\nconst glSurface = %s;\n", bytes.TrimSpace(data))
	if err = os.WriteFile(filepath.Join(dir, "gogl-surface.js"), []byte(content), 0644); err != nil {
		panic(err)
	}
}
